package com.kimo.mayapp

import android.content.Context

class AfghanPackage(
    val title: Tr,
    val price: Tr,
    val intro: Tr,
    val on: String,
    val off: String? = null,
    val check: String? = null
) {
    fun description(ctx: Context): String {
        val sb = StringBuilder(intro.get(ctx))

        val pressText = if (off != null) {
            PRESS_WITH_CODES
        } else {
            PRESS_GREEN
        }

        sb.append("\n").append(pressText.get(ctx))

        val line = if (off != null) DIAL_TWO else DIAL_ONE

        sb.append("\n")
            .append(
                line.get(ctx)
                    .replace("{on}", on)
                    .replace("{off}", off ?: "")
            )

        return sb.toString()
    }

    companion object {
        val PRESS_GREEN = Tr(
            "برای فعال‌سازی دکمه سبز را فشار دهید.",
            "To activate, press the green button.",
            "د فعالولو لپاره پر شنه تڼۍ کلیک وکړئ."
        )

        val PRESS_WITH_CODES = Tr(
            "برای استفاده از بسته، کد مربوطه را شماره‌گیری کنید.",
            "To use this package, dial the corresponding code.",
            "د دې بستې د کارولو لپاره اړوند کوډ ډایل کړئ."
        )

        val DIAL_ONE = Tr(
            "برای فعال‌سازی {on} را شماره‌گیری کنید.",
            "To activate, dial {on}.",
            "د فعالولو لپاره {on} ډایل کړئ."
        )

        val DIAL_TWO = Tr(
            "برای فعال‌سازی {on} و غیرفعال‌سازی {off} را شماره‌گیری کنید.",
            "To activate, dial {on}; to deactivate, dial {off}.",
            "د فعالولو لپاره {on} او د غیرفعالولو لپاره {off} ډایل کړئ."
        )
    }
}

